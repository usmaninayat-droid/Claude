import type { LatLng } from '@ds/components/map'

export type TruckStatus = 'moving' | 'idling' | 'stopped' | 'immobilized'

export interface Truck {
  id: string
  plate: string
  position: LatLng
  status: TruckStatus
  driver: string
  contact: string
  transporter: string
  activity: string
  location: string
  speed: number
  heading: number
  lastSeen: string
  odometer: number
  temperature: number
  altitude: number
  tags: string[]
  imei: string
  /**
   * A remote command has been dispatched to the telematics unit but the safety
   * interlock has NOT allowed it to execute yet (currently only `immobilize`,
   * queued while the vehicle is in motion). Cleared when the command fires or
   * the dispatcher cancels it.
   */
  pendingCommand?: 'immobilize' | null
  /** ISO-ish label ("14:32:07") shown in the queued banner + audit log. */
  pendingSince?: string
}

